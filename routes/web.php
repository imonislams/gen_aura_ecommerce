        Route::post('settings/showrooms', [ShowroomController::class, 'store'])->name('settings.showrooms.store');
        Route::put('settings/showrooms/{showroom}', [ShowroomController::class, 'update'])->name('settings.showrooms.update');
        Route::delete('settings/showrooms/{showroom}', [ShowroomController::class, 'destroy'])->name('settings.showrooms.destroy');
