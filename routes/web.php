        Route::post('settings/delivery-zones', [DeliveryZoneController::class, 'store'])->name('settings.delivery-zones.store');
        Route::put('settings/delivery-zones/{zone}', [DeliveryZoneController::class, 'update'])->name('settings.delivery-zones.update');
        Route::delete('settings/delivery-zones/{zone}', [DeliveryZoneController::class, 'destroy'])->name('settings.delivery-zones.destroy');
